# ratecov() with 3 waves vs RSiena RateX (directed): s501-s503, covariate = s50a wave-1 alcohol
library(RSiena)
data(s501); data(s502); data(s503); data(s50a)
write.csv(data.frame(x = s50a[, 1]), "dev/saom_rsiena_ratecov_mw_cov.csv", row.names = FALSE)
net <- sienaDependent(array(c(s501, s502, s503), dim = c(50, 50, 3)))
x <- coCovar(s50a[, 1])
d <- sienaDataCreate(net, x)
e <- getEffects(d)
e <- includeEffects(e, recip)
e <- includeEffects(e, RateX, interaction1 = "x", type = "rate")
res <- list()
for (sd in 1:3) {
	t0 <- Sys.time()
	alg <- sienaAlgorithmCreate(projname = NULL, seed = sd, n3 = 1000, nsub = 4)
	ans <- siena07(alg, data = d, effects = e, batch = TRUE, silent = TRUE)
	res[[sd]] <- c(ans$rate, ans$theta)
	cat(sprintf("seed %d  %.1f s  (cond=%s)\n", sd, as.numeric(Sys.time() - t0, units = "secs"), ans$cconditional))
}
m <- do.call(rbind, res); print(round(m, 3)); cat("MEAN\n"); print(round(colMeans(m), 3))
print(as.data.frame(e)[as.data.frame(e)$include, c("shortName", "type", "period")])
