# two co-evolving behaviors (alcohol, smoking) with the network: RSiena reference for nwsaom behavior(alc : ... | smk : ...)
library(RSiena)
data(s501); data(s502); data(s503); data(s50a); data(s50s)
net <- sienaDependent(array(c(s501, s502, s503), dim = c(50, 50, 3)))
alc <- sienaDependent(s50a, type = "behavior")
smk <- sienaDependent(s50s, type = "behavior")
write.csv(data.frame(a1 = s50a[,1], a2 = s50a[,2], a3 = s50a[,3], s1 = s50s[,1], s2 = s50s[,2], s3 = s50s[,3]), "dev/saom_rsiena_multibeh_data.csv", row.names = FALSE)
d <- sienaDataCreate(net, alc, smk)
e <- getEffects(d)
e <- includeEffects(e, recip, transTrip)
e <- includeEffects(e, avAlt, name = "alc", interaction1 = "net")
e <- includeEffects(e, avAlt, name = "smk", interaction1 = "net")
print(as.data.frame(e)[as.data.frame(e)$include, c("name", "shortName", "type")])
for (sd in 1:3) {
	t0 <- Sys.time()
	alg <- sienaAlgorithmCreate(projname = NULL, seed = sd, n3 = 1000, nsub = 4)
	ans <- try(siena07(alg, data = d, effects = e, batch = TRUE, silent = TRUE), silent = TRUE)
	if (inherits(ans, "try-error")) cat(sprintf("RSIENA seed %d failed\n", sd))
	else cat(sprintf("RSIENA seed %d (%.0fs) targets: %s\n  est: %s\n  names: %s\n", sd, as.numeric(Sys.time() - t0, units = "secs"), paste(round(ans$targets, 2), collapse = " "), paste(round(c(ans$rate, ans$theta), 3), collapse = " "), paste(ans$effects$effectName, collapse = " | ")))
}
